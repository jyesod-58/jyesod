"""Embed local large-file source fragments; delivered HTML remains standalone."""
from pathlib import Path
ROOT=Path(__file__).resolve().parent
START='/* BEGIN LARGE FILE SUPPORT (generated by build_detector.py) */'
END='/* END LARGE FILE SUPPORT */'
def build():
    p=ROOT/'pii_finder.html';text=p.read_text(encoding='utf-8')
    if START in text:
        a=text.index(START);b=text.index(END,a)+len(END);text=text[:a].rstrip()+'\n'+text[b:].lstrip()
    code='\n'.join((ROOT/name).read_text(encoding='utf-8') for name in ['large_storage_fragment.js','burp_stream_fragment.js','large_app_fragment.js'])
    if '</script' in code.lower():raise ValueError('An embedded fragment closes the HTML script')
    marker='setLoaded(false);\n})();'
    assert marker in text
    text=text.replace(marker,START+'\n'+code+'\n'+END+'\n'+marker)
    p.write_text(text,encoding='utf-8')
if __name__=='__main__':build()
